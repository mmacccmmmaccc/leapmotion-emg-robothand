void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
	if (huart->Instance == USART2)
	  {
	    if (rx_data == '\n' || rx_data == '\r') {
	      command_ready = 1;
	    } else {
	      if (rx_index < sizeof(rx_buffer) - 1) {
	        rx_buffer[rx_index++] = rx_data;
	      }
	    }
	    HAL_UART_Receive_IT(&huart2, &rx_data, 1); // Restart UART receive
	  }
}

void ParseAndSetServoAngles(uint8_t* cmd)
{
    // cmd is like: "80,100,90,85,70"
    // Null-terminate just in case (should already be done by UART)
    size_t len = strlen((char*)cmd);
    if (len < 5) return; // too short

    char* token = strtok((char*)cmd, ",");
    int idx = 0;
    while (token != NULL && idx < 5) {
        int angle = atoi(token);

//        if (openness < 0) openness = 0;
//        if (openness > 100) openness = 100;

//        int angle = ((openness/100) * 120) + 60; // map 0-100% to 0-180°

        switch (idx) {
            case 0: Servo_SetAngle(&hservo1, angle); break; // Thumb
            case 1: Servo_SetAngle(&hservo2, angle); break; // Index
            case 2: Servo_SetAngle(&hservo3, angle); break; // Middle
            case 3: Servo_SetAngle(&hservo4, angle); break; // Ring
            case 4: Servo_SetAngle(&hservo5, angle); break; // Pinky
            default: break;
        }
        idx++;
        token = strtok(NULL, ",");
    }
}


void Servo_Init(Servo_HandleTypeDef* hservo, TIM_HandleTypeDef* htim, uint32_t channel, uint16_t min_us, uint16_t max_us)
{
    hservo->htim = htim;
    hservo->Channel = channel;
    hservo->MinPulse = min_us;
    hservo->MaxPulse = max_us;

    HAL_TIM_PWM_Start(htim, channel);  // Start PWM
}

void Servo_SetAngle(Servo_HandleTypeDef* hservo, uint8_t angle)
{
	int16_t pulse_length = hservo->MinPulse + (angle * (hservo->MaxPulse - hservo->MinPulse))/180;
	__HAL_TIM_SET_COMPARE(hservo->htim, hservo->Channel, pulse_length);
}
