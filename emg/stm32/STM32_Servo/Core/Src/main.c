static void UART_Process_Byte(uint8_t b) {
    if (b == '\n') {
        // Trim optional '\r'
        if (rx_len > 0 && rx_line[rx_len - 1] == '\r') {
            rx_line[rx_len - 1] = '\0';
        } else {
            rx_line[rx_len] = '\0';
        }
        UART_Process_Line(rx_line);
        rx_len = 0; // reset for next line
        return;
    }

    if (rx_len < (RX_LINE_BUF_SZ - 1)) {
        rx_line[rx_len++] = (char)b;
    } else {
        // Overflow: reset the line to avoid stale data
        rx_len = 0;
    }
}

static void UART_Process_Line(const char *line) {
    // Accept empty lines gracefully
    if (line == NULL || line[0] == '\0') return;

    // atoi: handles "0", "1", "123", etc.
    int val = atoi(line);

    last_result = val;
    last_result_ready = 1;
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
    if (huart == &HUART_RX) {
        UART_Process_Byte(rx_byte);
        // re-arm RX for next byte
        HAL_UART_Receive_IT(&HUART_RX, &rx_byte, 1);
    }
}

